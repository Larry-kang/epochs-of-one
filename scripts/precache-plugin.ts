/**
 * Minimal, dependency-free offline support: emits `sw.js` that precaches every
 * build asset and every file under public/ (data included). Runtime makes zero
 * requests to any other origin.
 */
import { createHash } from 'node:crypto';
import { readdirSync, statSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

export function precachePlugin(): Plugin {
  return {
    name: 'ledger-precache',
    apply: 'build',
    generateBundle(_opts, bundle) {
      const publicDir = join(process.cwd(), 'public');
      const files = new Set<string>(['./', './index.html']);
      const h = createHash('sha256');
      for (const k of Object.keys(bundle).sort()) {
        files.add('./' + k);
        const item = bundle[k]!;
        h.update(k);
        h.update(item.type === 'chunk' ? item.code : typeof item.source === 'string' ? item.source : Buffer.from(item.source));
      }
      for (const f of walk(publicDir).sort()) {
        const rel = relative(publicDir, f).split('\\').join('/');
        files.add('./' + rel);
        h.update(rel);
        h.update(readFileSync(f));
      }
      const version = h.digest('hex').slice(0, 16);
      const list = JSON.stringify([...files].sort(), null, 0);
      const code = `// generated by scripts/precache-plugin.ts — do not edit
const CACHE = 'ledger-${version}';
const FILES = ${list};
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (url.origin !== self.location.origin || e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true, ignoreVary: true }).then((r) => r || fetch(e.request).catch((err) => { if (e.request.mode === 'navigate') return caches.match('./index.html', { ignoreVary: true }); throw err; })));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: code });
    },
  };
}
